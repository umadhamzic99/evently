import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { QRSecurityManager } from '../src/core/qr-security.js';
import { createEvent } from '../src/core/event-registry.js';
import { WaitlistEngine } from '../src/core/waitlist-engine.js';
