// Polyfill minimal GAS Utilities & Cache for unit testing GAS modules in Node
(globalThis as any).Utilities = {
  base64EncodeWebSafe(bytes: number[] | string): string {
    const buf = typeof bytes === 'string' ? Buffer.from(bytes, 'utf8') : Buffer.from(bytes);
    return buf.toString('base64url');
  },
  base64DecodeWebSafe(input: string): number[] {
    const buf = Buffer.from(input, 'base64url');
    return Array.from(buf);
  },
  computeHmacSha256Signature(value: string, key: string): number[] {
    const hmac = crypto.createHmac('sha256', key).update(value).digest();
    return Array.from(hmac);
  },
  newBlob(data: number[] | string) {
    const buf = typeof data === 'string' ? Buffer.from(data, 'utf8') : Buffer.from(data);
    return {
      getBytes: () => Array.from(buf),
      getDataAsString: () => buf.toString('utf8'),
    };
  },
};

// Import GasQRSecurityManager dynamically after polyfilling Utilities
import { GasQRSecurityManager } from '../src/gas/qr-security-gas.js';

describe('GAS Plumbing: Security, Deduplication & Cross-Compatibility', () => {
  const secretKey = 'test_secret_key_for_gas_plumbing_12345';
  const nodeQR = new QRSecurityManager(secretKey);
  const gasQR = new GasQRSecurityManager(secretKey);

  test('GAS QR Manager verifies tokens generated by Node QR Manager (Cross-Environment Parity)', () => {
    const nodeToken = nodeQR.generateDynamicToken('reg_001', 'evt_100', 'EMP-1234', 3600);
    const mockCache = new Map<string, string>();
    const cacheAdapter = {
      get: (k: string) => mockCache.get(k) ?? null,
      put: (k: string, v: string) => { mockCache.set(k, v); },
    };

    const result = gasQR.verifyAndConsumeToken(
      nodeToken,
      'evt_100',
      'VOLUNTEER_1',
      'Door A',
      undefined,
      undefined,
      cacheAdapter
    );

    assert.equal(result.valid, true);
    assert.equal(result.scanResult, 'SUCCESS');
    assert.equal(result.payload?.uid, 'EMP-1234');
    assert.equal(result.payload?.tid, 'reg_001');
  });

  test('Node QR Manager verifies tokens generated by GAS QR Manager', () => {
    const gasToken = gasQR.generateDynamicToken('reg_002', 'evt_100', 'EMP-5678', 3600);
    const result = nodeQR.verifyAndConsumeToken(gasToken, 'evt_100', 'VOLUNTEER_1', 'Door A');

    assert.equal(result.valid, true);
    assert.equal(result.scanResult, 'SUCCESS');
    assert.equal(result.payload?.uid, 'EMP-5678');
  });

  test('Cache-based deduplication catches duplicate scans without PropertiesService', () => {
    const mockCache = new Map<string, string>();
    const cacheAdapter = {
      get: (k: string) => mockCache.get(k) ?? null,
      put: (k: string, v: string) => { mockCache.set(k, v); },
    };

    const token = gasQR.generateDynamicToken('reg_003', 'evt_100', 'EMP-9999', 3600);

    // Scan 1: Admitted
    const firstScan = gasQR.verifyAndConsumeToken(
      token, 'evt_100', 'VOL_1', 'Door 1', undefined, undefined, cacheAdapter
    );
    assert.equal(firstScan.valid, true);
    assert.equal(firstScan.scanResult, 'SUCCESS');

    // Scan 2: Duplicate blocked
    const secondScan = gasQR.verifyAndConsumeToken(
      token, 'evt_100', 'VOL_2', 'Door 2', undefined, undefined, cacheAdapter
    );
    assert.equal(secondScan.valid, false);
    assert.equal(secondScan.scanResult, 'DUPLICATE_REJECTED');
  });
});

describe('GAS Plumbing: Waitlist FIFO Promotion on Cancellation', () => {
  test('Cancelling an active registration auto-promotes waitlist #1 and shifts queue', () => {
    const event = createEvent({
      eventTypeSlug: 'manager_workshop',
      title: 'Workshop',
      ownerUserId: 'LEAD-1',
      startDate: '2026-11-01',
      endDate: '2026-11-01',
      maxCapacity: 1, // Only 1 spot
    });

    const regs: Registration[] = [
      {
        id: 'reg_active',
        eventId: event.id,
        participantUserId: 'EMP-ACTIVE',
        isExternal: false,
        status: 'registered',
        registeredAt: '2026-10-26T08:00:00Z',
        customFields: {},
        qrSecretSalt: 'salt1',
      },
      {
        id: 'reg_wl_1',
        eventId: event.id,
        participantUserId: 'EMP-WL-1',
        isExternal: false,
        status: 'waitlisted',
        waitlistPosition: 1,
        registeredAt: '2026-10-26T08:05:00Z',
        customFields: {},
        qrSecretSalt: 'salt2',
      },
      {
        id: 'reg_wl_2',
        eventId: event.id,
        participantUserId: 'EMP-WL-2',
        isExternal: false,
        status: 'waitlisted',
        waitlistPosition: 2,
        registeredAt: '2026-10-26T08:10:00Z',
        customFields: {},
        qrSecretSalt: 'salt3',
      },
    ];

    const result = WaitlistEngine.cancel(
      event,
      'reg_active',
      'User cannot attend',
      regs,
      'COORDINATOR_1'
    );

    assert.equal(result.cancelled.status, 'cancelled');
    assert.equal(result.promoted?.id, 'reg_wl_1');
    assert.equal(result.promoted?.status, 'registered');
  });
});
